# --- Enums for Status and Priority ---

class IdeaStatus(Enum):
    """Represents the current status of an Idea."""
    PENDING = "PENDING"             # Idea submitted, awaiting assignment to an agent.
    WAITING_DEPENDENCIES = "WAITING_DEPENDENCIES" # Idea's prerequisites (other ideas) not yet met.
    ASSIGNED = "ASSIGNED"           # Idea assigned to an agent, but agent hasn't started execution.
    IN_PROGRESS = "IN_PROGRESS"     # Agent is actively working on the idea.
    COMPLETED = "COMPLETED"         # Idea successfully processed by an agent.
    FAILED = "FAILED"               # Idea processing failed due to an error.
    CANCELLED = "CANCELLED"         # Idea was cancelled, typically during manager shutdown.

class IdeaPriority(Enum):
    """Represents the priority level of an Idea."""
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"

class AgentStatus(Enum):
    """Represents the current operational status of an Agent."""
    IDLE = "IDLE"           # Agent is available to take new ideas.
    WORKING = "WORKING"     # Agent is currently processing an idea.
    OFFLINE = "OFFLINE"     # Agent is not available (not currently used, but useful for future features).

# --- Data Classes for Idea and Agent Definition ---

@dataclass
class Idea:
    """
    Represents a discrete unit of work, a task, or a problem to be solved by an Agent.
    """
    description: str = field()
    id: str = field(default_factory=lambda: str(uuid.uuid4()))
    status: IdeaStatus = field(default=IdeaStatus.PENDING)
    priority: IdeaPriority = field(default=IdeaPriority.MEDIUM)
    capabilities_required: Set[str] = field(default_factory=set) # Set of capabilities an agent must have to handle this idea.
    dependencies: Set[str] = field(default_factory=set) # IDs of other ideas that must be in COMPLETED status before this idea can start.
    assigned_agent_id: Optional[str] = field(default=None) # The ID of the agent currently assigned to this idea.
    result: Any = field(default=None) # The output or result generated by the agent upon completion.
    error_message: Optional[str] = field(default=None) # Message if the idea failed.
    created_at: datetime = field(default_factory=datetime.now)
    updated_at: datetime = field(default_factory=datetime.now)

    def update_status(self, new_status: IdeaStatus, agent_id: Optional[str] = None, result: Any = None, error_message: Optional[str] = None):
        """
        Updates the idea's status and relevant fields.
        Ensures 'updated_at' timestamp is always current.
        """
        self.status = new_status
        self.updated_at = datetime.now()
        if agent_id:
            self.assigned_agent_id = agent_id
        if result is not None:
            self.result = result
        if error_message:
            self.error_message = error_message
        logger.debug(f"Idea {self.id} status updated to {new_status.value}")


class BaseAgent(ABC):
    """
    Abstract Base Class (ABC) for all Agents.
    Defines the common interface and properties for agents managed by the AutonomyManager.
    All concrete agents must inherit from this class and implement the `execute_idea` method.
    """
    def __init__(self, agent_id: str, name: str, capabilities: Set[str]):
        if not agent_id:
            raise ValueError("Agent ID cannot be empty.")
        if not name:
            raise ValueError("Agent name cannot be empty.")
        if not isinstance(capabilities, set):
            raise TypeError("Capabilities must be a set of strings.")
        if not all(isinstance(cap, str) for cap in capabilities):
            raise ValueError("All capabilities must be strings.")

        self._id = agent_id
        self._name = name
        self._capabilities = frozenset(capabilities) # Use frozenset for immutability
        self._status: AgentStatus = AgentStatus.IDLE
        self._current_idea_id: Optional[str] = None
        logger.info(f"Agent '{self._name}' ({self._id}) initialized with capabilities: {', '.join(self._capabilities)}")

    @property
    def id(self) -> str:
        """Returns the unique identifier of the agent."""
        return self._id

    @property
    def name(self) -> str:
        """Returns the human-readable name of the agent."""
        return self._name

    @property
    def capabilities(self) -> Set[str]:
        """Returns the set of capabilities this agent possesses."""
        return set(self._capabilities) # Return a copy to prevent external modification

    @property
    def status(self) -> AgentStatus:
        """Returns the current operational status of the agent."""
        return self._status

    @status.setter
    def status(self, new_status: AgentStatus):
        """Sets the new operational status for the agent."""
        self._status = new_status
        logger.debug(f"Agent '{self.name}' ({self.id}) status updated to {new_status.value}")

    @property
    def current_idea_id(self) -> Optional[str]:
        """Returns the ID of the idea the agent is currently working on, or None if idle."""
        return self._current_idea_id

    @current_idea_id.setter
    def current_idea_id(self, idea_id: Optional[str]):
        """Sets the ID of the idea the agent is currently working on."""
        self._current_idea_id = idea_id

    @abstractmethod
    async def execute_idea(self, idea: Idea) -> Any:
        """
        Abstract method for an agent to process an idea.
        This method must be implemented by concrete agent classes to define their specific logic.
        It should perform the actual work corresponding to the idea's description and
        required capabilities, and return a result upon successful completion.
        It is an async method to allow for non-blocking operations (e.g., I/O, external API calls).
        """
        pass

