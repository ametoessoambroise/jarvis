class SimpleTaskAgent(BaseAgent):
    """
    A simple concrete agent that simulates performing various tasks based on the idea description
    and required capabilities. It can handle 'calculation', 'greeting', and 'general_task'.
    It also includes a specific trigger for simulated failures.
    """
    def __init__(self, agent_id: str, name: str):
        super().__init__(agent_id, name, {"calculation", "greeting", "general_task", "error_simulation"})

    async def execute_idea(self, idea: Idea) -> Any:
        """
        Simulates execution of an idea.
        The execution time varies based on the description length.
        Raises an exception if an unsupported task is requested or a simulated error occurs.
        """
        logger.info(f"Agent '{self.name}' ({self.id}) starting idea '{idea.id}': '{idea.description}'")
        try:
            # Simulate varying work time based on description length
            await asyncio.sleep(0.5 + len(idea.description) % 3)

            if "calculate" in idea.description.lower() and "calculation" in self.capabilities:
                # Basic parsing for calculation, expecting "calculate X Y"
                parts = idea.description.lower().split()
                try:
                    calculate_idx = parts.index("calculate")
                    num1 = float(parts[calculate_idx + 1])
                    num2 = float(parts[calculate_idx + 2])
                    result = num1 + num2
                    logger.info(f"Agent '{self.name}' performed calculation for idea '{idea.id}': {num1} + {num2} = {result}")
                    return f"Calculation result: {result}"
                except (ValueError, IndexError):
                    raise ValueError("Invalid calculation request in idea description. Expected 'calculate X Y'.")
            elif "greet" in idea.description.lower() and "greeting" in self.capabilities:
                # Extract target for greeting, e.g., "Greet Bob"
                target = idea.description.split("greet", 1)[1].strip() or "world"
                result = f"Hello, {target} from {self.name}!"
                logger.info(f"Agent '{self.name}' performed greeting for idea '{idea.id}': {result}")
                return result
            elif "fail" in idea.description.lower() or "error simulation" in idea.description.lower():
                # Simulate an intentional failure
                raise RuntimeError("Simulated failure during idea execution.")
            elif "general_task" in idea.capabilities_required and "general_task" in self.capabilities:
                # General purpose task handling
                result = f"Agent '{self.name}' processed general task: '{idea.description}'"
                logger.info(f"Agent '{self.name}' processed general task for idea '{idea.id}'")
                return result
            else:
                # If no specific handling, or capabilities mismatch (should ideally not happen if manager assigns correctly)
                raise ValueError(f"Agent '{self.name}' does not know how to handle idea: '{idea.description}' or lacks required capabilities.")
        except Exception as e:
            logger.error(f"Agent '{self.name}' failed to execute idea '{idea.id}': {e}", exc_info=True)
            raise # Re-raise the exception to be caught by the manager's task monitor


# --- Autonomy Manager ---

class AutonomyManager:
    """
    The central manager responsible for orchestrating Agents and Ideas.
    It handles idea submission, agent assignment, monitoring, and result collection.
    It operates asynchronously to manage concurrent tasks efficiently.
    """
    def __init__(self):
        self._ideas: Dict[str, Idea] = {}                       # Stores all ideas by their unique ID.
        self._agents: Dict[str, BaseAgent] = {}                 # Stores all registered agents by their unique ID.
        self._pending_ideas_queue: asyncio.Queue[Idea] = asyncio.Queue() # Queue for ideas awaiting assignment.
        self._background_tasks: Set[asyncio.Task] = set()       # Tracks manager's own persistent background tasks (e.g., idea processor).
        self._agent_execution_tasks: Dict[str, asyncio.Task] = {} # Tracks active `execute_idea` tasks for each idea.
        self.enabled: bool = True
        self.sensitivity: int = 5

        logger.info("AutonomyManager initialized.")

    async def _process_unassigned_ideas(self):
        """
        Continuously monitors the `_pending_ideas_queue` and attempts to assign ideas
        to available and suitable agents.
        Handles dependencies by re-queueing ideas if dependencies are not met.
        This runs as a long-lived background task.
        """
        while True:
            try:
                # Wait for an idea from the queue. Timeout allows periodic checks/shutdown.
                idea = await asyncio.wait_for(self._pending_ideas_queue.get(), timeout=1.0)

                # Check if the idea has unmet dependencies.
                if idea.dependencies:
                    unmet_deps = [
                        dep_id for dep_id in idea.dependencies
                        if dep_id not in self._ideas or self._ideas[dep_id].status != IdeaStatus.COMPLETED
                    ]
                    if unmet_deps:
                        logger.debug(f"Idea '{idea.id}' waiting for dependencies: {unmet_deps}. Re-queueing as WAITING_DEPENDENCIES.")
                        idea.update_status(IdeaStatus.WAITING_DEPENDENCIES)
                        # Re-add to queue after a short delay to avoid busy-waiting for dependencies.
                        # This also allows other ideas to be processed.
                        await asyncio.sleep(0.1)
                        self._pending_ideas_queue.put_nowait(idea)
                        self._pending_ideas_queue.task_done() # Mark retrieved item as done so the queue knows it's processed (even if re-queued)
                        continue

                # Attempt to find an agent for the idea.
                agent = self._find_suitable_agent(idea)
                if agent:
                    await self._assign_idea(idea, agent)
                    self._pending_ideas_queue.task_done() # Mark the idea as processed from the queue.
                else:
                    logger.warning(f"No suitable or available agent found for idea '{idea.id}' (Caps: {idea.capabilities_required}). Re-queueing.")
                    # If no agent is available, put it back to try later.
                    await asyncio.sleep(0.5) # Prevent high CPU usage if no agents are ever available.
                    self._pending_ideas_queue.put_nowait(idea)
                    self._pending_ideas_queue.task_done() # Mark as done from queue
            except asyncio.TimeoutError:
                # No ideas in the queue for the timeout period, just continue looping.
                pass
            except asyncio.CancelledError:
                logger.info("'_process_unassigned_ideas' task cancelled. Manager is shutting down.")
                break
            except Exception as e:
                logger.error(f"Unhandled error in _process_unassigned_ideas loop: {e}", exc_info=True)
                await asyncio.sleep(1.0) # Prevent a tight error loop in case of unexpected exceptions.

    def register_agent(self, agent: BaseAgent):
        """
        Registers an agent with the manager.
        Raises ValueError if an agent with the same ID is already registered.
        """
        if agent.id in self._agents:
            raise ValueError(f"Agent with ID '{agent.id}' is already registered.")
        self._agents[agent.id] = agent
        logger.info(f"Agent '{agent.name}' ({agent.id}) registered successfully.")

    async def submit_idea(self,
                          description: str,
                          priority: IdeaPriority = IdeaPriority.MEDIUM,
                          capabilities_required: Optional[Set[str]] = None,
                          dependencies: Optional[Set[str]] = None) -> Idea:
        """
        Submits a new idea to the manager for processing.
        Returns the created Idea object.
        Raises ValueError if any specified dependency idea does not exist.
        """
        if dependencies:
            for dep_id in dependencies:
                if dep_id not in self._ideas:
                    raise ValueError(f"Dependency idea '{dep_id}' not found. Please ensure all dependencies are submitted first.")
        
        # Ensure capabilities and dependencies are always sets
        _capabilities_required = capabilities_required if capabilities_required is not None else set()
        _dependencies = dependencies if dependencies is not None else set()

        idea = Idea(
            description=description,
            priority=priority,
            capabilities_required=_capabilities_required,
            dependencies=_dependencies
        )
        self._ideas[idea.id] = idea
        await self._pending_ideas_queue.put(idea) # Add to queue for processing, `await` for potential full queue.
        logger.info(f"Idea '{idea.id}' submitted (priority: {priority.value}, caps: {capabilities_required}).")
        return idea

    def get_idea(self, idea_id: str) -> Optional[Idea]:
        """Retrieves an idea by its unique ID."""
        return self._ideas.get(idea_id)

    def get_agent(self, agent_id: str) -> Optional[BaseAgent]:
        """Retrieves an agent by its unique ID."""
        return self._agents.get(agent_id)

    def get_all_ideas(self) -> List[Idea]:
        """Returns a list of all ideas managed by the system."""
        return list(self._ideas.values())

    def get_all_agents(self) -> List[BaseAgent]:
        """Returns a list of all agents currently registered with the system."""
        return list(self._agents.values())

    def _find_suitable_agent(self, idea: Idea) -> Optional[BaseAgent]:
        """
        Finds an idle agent that possesses all required capabilities for the given idea.
        Prioritizes agents based on internal logic (e.g., specific skills, load balancing).
        For this implementation, it picks the first suitable and available agent found.
        """
        # Iterate over agents, potentially sorting by priority or other metrics if needed.
        # For simplicity, we just find the first available agent matching capabilities.
        for agent in self._agents.values():
            if agent.status == AgentStatus.IDLE:
                # Check if the agent's capabilities include ALL required capabilities for the idea.
                if idea.capabilities_required.issubset(agent.capabilities):
                    logger.debug(f"Found suitable agent '{agent.name}' ({agent.id}) for idea '{idea.id}'.")
                    return agent
        logger.debug(f"No suitable IDLE agent found for idea '{idea.id}'. Required capabilities: {idea.capabilities_required}")
        return None

    async def _assign_idea(self, idea: Idea, agent: BaseAgent):
        """
        Assigns an idea to a selected agent and initiates its execution in a background task.
        Updates the statuses of both the idea and the agent.
        """
        logger.info(f"Assigning idea '{idea.id}' to agent '{agent.name}' ({agent.id}).")

        # Update idea and agent statuses to reflect the assignment.
        idea.update_status(IdeaStatus.ASSIGNED, agent_id=agent.id)
        agent.status = AgentStatus.WORKING
        agent.current_idea_id = idea.id

        # Create an asyncio task to execute the agent's logic for this idea.
        # This allows the manager to continue processing other ideas while the agent works.
        task = asyncio.create_task(self._execute_agent_idea_wrapper(agent, idea))
        self._agent_execution_tasks[idea.id] = task # Track the task using the idea ID.
        self._background_tasks.add(task) # Add to general background tasks for proper cleanup during shutdown.
        task.add_done_callback(self._background_tasks.discard) # Automatically remove task from set when it finishes.

    async def _execute_agent_idea_wrapper(self, agent: BaseAgent, idea: Idea):
        """
        A wrapper coroutine around `agent.execute_idea`.
        It handles idea status updates (IN_PROGRESS, COMPLETED, FAILED, CANCELLED),
        captures results or error messages, and ensures agent status is reset to IDLE.
        """
        try:
            logger.info(f"Agent '{agent.name}' ({agent.id}) is now IN_PROGRESS on idea '{idea.id}'.")
            idea.update_status(IdeaStatus.IN_PROGRESS)

            # Await the actual agent's execution method.
            result = await agent.execute_idea(idea)

            # If execution completes without error, mark the idea as COMPLETED.
            idea.update_status(IdeaStatus.COMPLETED, result=result)
            logger.info(f"Idea '{idea.id}' completed by agent '{agent.name}'. Result: {str(result)[:100]}...")
        except asyncio.CancelledError:
            # This exception is raised if the task is cancelled (e.g., during manager shutdown).
            idea.update_status(IdeaStatus.CANCELLED)
            logger.warning(f"Idea '{idea.id}' processing by agent '{agent.name}' was cancelled.")
        except Exception as e:
            # Catch any other exceptions raised by the agent's `execute_idea` method.
            idea.update_status(IdeaStatus.FAILED, error_message=str(e))
            logger.error(f"Idea '{idea.id}' failed during execution by agent '{agent.name}': {e}", exc_info=True)
        finally:
            # Ensure agent status is reset and current_idea_id is cleared, regardless of outcome.
            agent.current_idea_id = None
            agent.status = AgentStatus.IDLE
            self._agent_execution_tasks.pop(idea.id, None) # Remove task from active agent tasks tracking.

    async def start(self):
        """
        Starts the AutonomyManager's background processing tasks.
        This includes the continuous idea assignment loop.
        """
        logger.info("AutonomyManager starting...")
        # Create and track the long-running task for processing unassigned ideas.
        processor_task = asyncio.create_task(self._process_unassigned_ideas(), name="IdeaProcessor")
        self._background_tasks.add(processor_task)
        processor_task.add_done_callback(self._background_tasks.discard) # Remove from set when done/cancelled.
        logger.info("AutonomyManager started background tasks.")

    def enable(self) -> str:
        self.enabled = True
        logger.info("AutonomyManager enabled.")
        return "Autonomy manager enabled."

    def disable(self) -> str:
        self.enabled = False
        logger.info("AutonomyManager disabled.")
        return "Autonomy manager disabled."

    def set_sensitivity(self, level: int) -> str:
        if level < 1:
            level = 1
        elif level > 10:
            level = 10
        self.sensitivity = level
        logger.info(f"AutonomyManager sensitivity set to {level}.")
        return f"Sensitivity set to {level}."

    def get_status(self) -> Dict[str, Any]:
        return {
            "enabled": self.enabled,
            "sensitivity": self.sensitivity,
            "ideas_count": len(self._ideas),
            "pending_ideas": sum(1 for idea in self._ideas.values() if idea.status == IdeaStatus.PENDING),
            "active_agents": sum(1 for agent in self._agents.values() if agent.status == AgentStatus.WORKING),
        }

    async def stop(self):
        """
        Gracefully stops the AutonomyManager and its background tasks.
        It cancels all active manager and agent tasks and waits for them to complete cancellation.
        Ensures a clean shutdown, marking any pending ideas as CANCELLED.
        """
        logger.info("AutonomyManager stopping...")

        # Log status of agents still working for awareness.
        for agent in self._agents.values():
            if agent.status == AgentStatus.WORKING:
                logger.warning(f"Agent '{agent.name}' ({agent.id}) is still working on idea '{agent.current_idea_id}' during shutdown.")
                # In a more advanced system, you might try to persist agent state or interrupt more forcefully.

        # Cancel all background tasks managed by the manager.
        if self._background_tasks:
            # Create a list copy to iterate, as tasks remove themselves from _background_tasks.
            tasks_to_cancel = [task for task in self._background_tasks if not task.done()]
            if tasks_to_cancel:
                logger.info(f"Cancelling {len(tasks_to_cancel)} active background tasks...")
                for task in tasks_to_cancel:
                    task.cancel()
                # Await all cancelled tasks to ensure they handle their `CancelledError` and clean up.
                await asyncio.gather(*tasks_to_cancel, return_exceptions=True)
                logger.info("All background tasks cancelled and awaited.")

        # Process any remaining ideas in the queue as cancelled during shutdown.
        while not self._pending_ideas_queue.empty():
            try:
                idea = self._pending_ideas_queue.get_nowait()
                if idea.status in [IdeaStatus.PENDING, IdeaStatus.WAITING_DEPENDENCIES]:
                    idea.update_status(IdeaStatus.CANCELLED)
                    logger.warning(f"Idea '{idea.id}' was in pending queue during shutdown, marked as CANCELLED.")
                self._pending_ideas_queue.task_done()
            except asyncio.QueueEmpty:
                break

        logger.info("AutonomyManager stopped.")

